# Q1 — import

# You already know Python's built-in math module.

# Write a program that:

# Imports math.

# Takes the number:

# number = 25
# Finds its square root using math.sqrt().
# Finds 5! using math.factorial().
# Prints both results.

# Expected:

# Square root: 5.0
# Factorial: 120
# Don't use:
# 5 ** 0.5

# Use the module:

# math.sqrt()
# math.factorial()

# Try it yourself.

import math

number = 5
print(math.sqrt(number))
print(math.factorial(number))